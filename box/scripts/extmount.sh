#!/system/bin/sh
# Монтирует медиадиск (ext4) под прежним именем точки и настраивает накопитель.
#
# Диск переведён на ext4 10.09.2026 — ради разреженных файлов (на exFAT каждый новый
# файл раздачи физически забивался нулями по 7 секунд на гигабайт) и журнала.
# Вечером того же дня выяснилось, что vold этой прошивки ext4 монтирует и сам —
# в /mnt/media_rw/<UUID> и /storage/<UUID>. Наш монтировщик нужен ради двух вещей:
#
#  1) Имя точки FA9E-9466 (это был серийник exFAT-тома): так пути в скриптах качалки
#     и в базе медиатеки Kodi остались без единой правки. Второе монтирование того же
#     раздела для ядра безвредно — суперблок один. Проброс в /mnt/user/0/<имя> — то,
#     что делает vold: оттуда приложения видят диск как /storage/<имя>.
#
#  2) TRIM. В боксе не винчестер, а NVMe-накопитель за мостом JMicron JMS583, и ядро
#     через usb-storage команду освобождения (UNMAP) ему по умолчанию не шлёт —
#     provisioning_mode=full. Без неё накопитель считает все когда-либо записанные
#     блоки занятыми: после того как на exFAT было записано 870 ГБ, а потом диск
#     переформатирован, он думал, что забит под завязку, и каждую запись делал через
#     сборку мусора — 1,6 секунды на кусок в 700 КБ, 2-5 МБ/с. Именно это выглядело
#     как «тротлинг через 10 минут» и лечилось «отдыхом»: в паузе накопитель успевал
#     освободить немного блоков. Проверено 10.09.2026: мост UNMAP принимает, соседние
#     данные целы. Поэтому включаем unmap и монтируем с discard — удалённое
#     освобождается сразу.
DEV=/dev/block/sda1
NAME=FA9E-9466
RAW=/mnt/media_rw/$NAME
USR=/mnt/user/0/$NAME
LOG=/data/local/tmp/aria2/extmount.log
# Общие функции — журнал, обращение к качалке и к Kodi, ротация, проверка диска.
# Вынесены в один файл 14.09.2026: до этого копии жили в девяти скриптах и расходились
# в мелочах (обрезка заголовков HTTP, таймауты), из-за чего работали по случайности.
. /data/local/tmp/aria2/lib.sh

mounted() { grep -q " $1 " /proc/mounts; }

log "монтировщик запущен"
while :; do
    if [ -b "$DEV" ]; then
        if ! mounted "$RAW"; then
            type=$(blkid -s TYPE -o value "$DEV" 2>/dev/null)
            if [ "$type" = "ext4" ]; then
                # TRIM через мост — до монтирования, чтобы discard заработал с первой записи
                for p in /sys/block/sda/device/scsi_disk/*/provisioning_mode; do
                    echo unmap > "$p" 2>/dev/null && log "unmap включён ($(cat "$p"))"
                done
                mkdir -p "$RAW"
                # commit=60: коммит журнала раз в минуту вместо пяти секунд — меньше прыжков
                # головок для SMR-диска. Цена: после паники теряется до минуты метаданных,
                # для медиатеки это ничто (качалка перепроверит куски сама).
                if mount -t ext4 -o noatime,nodiratime,discard,commit=60 "$DEV" "$RAW" 2>>"$LOG"; then
                    # Качалка работает от shell (2000) с группой media_rw (1023), Kodi читает
                    # как «прочие» — у него есть только группа external_storage. Бит setgid
                    # на каталоге даёт новым файлам группу media_rw автоматически.
                    chown 2000:1023 "$RAW"; chmod 2775 "$RAW"
                    # Очередь блочного устройства. Для этого USB-накопителя ядро выставляет
                    # nr_requests=2 (драйвер usb-storage без очереди команд), и запись
                    # падает: мелкие запросы не группируются. Значение живёт до
                    # перезагрузки, поэтому ставим тут.
                    echo 128 > /sys/block/sda/queue/nr_requests 2>/dev/null
                    echo 512 > /sys/block/sda/queue/read_ahead_kb 2>/dev/null
                    log "смонтирован $DEV -> $RAW ($(grep " $RAW " /proc/mounts | awk '{print $4}'))"
                else
                    log "не смонтировался $DEV, повтор через 30 с"; sleep 30; continue
                fi
            else
                log "на $DEV не ext4 (${type:-нет ФС}) — не трогаю"; sleep 60; continue
            fi
        fi
        # Проброс приложениям — только когда пользовательское пространство уже поднято.
        if mounted "$RAW" && [ -d /mnt/user/0 ] && ! mounted "$USR"; then
            mkdir -p "$USR" && mount --bind "$RAW" "$USR" 2>>"$LOG" \
              && log "проброшен в $USR (для приложений это /storage/$NAME)"
        fi
    else
        # Диск вынули или он отвалился по питанию — снимаем оставшиеся точки,
        # иначе при возвращении диска mount упрётся в занятую точку.
        if mounted "$USR"; then umount -l "$USR" 2>/dev/null; log "диск исчез — снял $USR"; fi
        if mounted "$RAW"; then umount -l "$RAW" 2>/dev/null; log "диск исчез — снял $RAW"; fi
    fi
    sleep 10
done
