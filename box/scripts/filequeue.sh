#!/system/bin/sh
# Держит включённой ровно одну незавершённую серию: следующая включается только
# когда предыдущая докачана.
#
# Зачем. На exFAT нет разреженных файлов, а libtorrent растягивает каждый
# включённый файл до полного размера сразу. Растягивание = физическая запись
# нулей, около 7 секунд на гигабайт. Десять серий по 9 ГБ = полтора часа
# обнуления, за которые диск занят целиком: закачка стоит, кино не проигрывается,
# а один раз приставка на этом упала в панику. С одной серией обнуляется 9 ГБ,
# то есть минута. Заодно запись идёт в один файл, а не в десять вразнобой.
#
# Завершённые серии переводятся в приоритет «не качать»: тогда раскладка может
# безопасно унести их в медиатеку — качалка не хватится файла и не начнёт
# качать его заново.
BIN=/data/local/tmp/aria2
# Общие функции — журнал, обращение к качалке и к Kodi, ротация, проверка диска.
# Вынесены в один файл 14.09.2026: до этого копии жили в девяти скриптах и расходились
# в мелочах (обрезка заголовков HTTP, таймауты), из-за чего работали по случайности.
. /data/local/tmp/aria2/lib.sh
api()      { qbt_get "$1"; }
api_post() { qbt_post "$1" "$2"; }

LOG=${FQ_LOG:-$BIN/filequeue.log}
QBT=127.0.0.1:8080
SLEEP=${FQ_SLEEP:-60}
DRY=${FQ_DRY:-0}



# Хеши всех раздач. Именно всех, а не только качающихся: когда единственная
# включённая серия докачана, качалка считает раздачу завершённой и переводит её
# в «раздаётся» — если смотреть только на качающиеся, следующая серия никогда
# не включится. Раздачи, у которых докачано всё, отсекаются ниже по прогрессу.
all_hashes() {
    api torrents/info | sed 's/},{/\n/g' \
      | awk '{ if (match($0,/"hash":"[0-9a-fA-F]+"/)) print substr($0,RSTART+8,RLENGTH-9) }'
}

# Строки «индекс прогресс приоритет» по каждому файлу раздачи.
# Серии из series/<хеш>.skip уже лежат в медиатеке (раздачу обновил series.sh) — считаем их
# докачанными: иначе очередь включила бы их и скачала заново.
file_table() {
    api "torrents/files?hash=$1" | sed 's/},{/\n/g' \
      | awk -v skip=" $(tr '\n' ' ' < "$BIN/series/$1.skip" 2>/dev/null) " '{
          i=""; p=""; r="";
          if (match($0,/"index":[0-9]+/))               i=substr($0,RSTART+8,RLENGTH-8);
          if (match($0,/"progress":[0-9.eE+-]+/))       p=substr($0,RSTART+11,RLENGTH-11);
          if (match($0,/"priority":[0-9]+/))            r=substr($0,RSTART+11,RLENGTH-11);
          if (index(skip, " " i " ")) p=1;
          if (i != "" && p != "" && r != "") print i, p, r
        }'
}

queue_one() {
    h="$1"
    tbl=$(file_table "$h")
    [ -z "$tbl" ] && return 0
    total=$(printf '%s\n' "$tbl" | wc -l)

    # Первая по порядку недокачанная серия — её и качаем.
    target=$(printf '%s\n' "$tbl" | awk '$2 < 1 {print $1; exit}')
    if [ -z "$target" ]; then
        log "раздача $h: все файлы докачаны, очередь не нужна"
        return 0
    fi

    # Менять что-то нужно, только если цель выключена или включён кто-то ещё.
    need=$(printf '%s\n' "$tbl" | awk -v t="$target" '
        { if ($1==t && $3==0) c=1; if ($1!=t && $3!=0) c=1 } END{ print c+0 }')
    [ "$need" = 0 ] && return 0

    off=$(printf '%s\n' "$tbl" | awk -v t="$target" '$1!=t && $3!=0 {printf "%s|", $1}')
    # mksh не режет строку по «|» в подстановке — ${off%|} молча возвращает всё как было,
    # поэтому последнюю палку снимаем через sed.
    off=$(printf '%s' "$off" | sed 's/|$//')

    if [ "$DRY" = 1 ]; then
        log "СУХОЙ ПРОГОН: включить индекс $target, выключить индексы [$off] (всего файлов $total)"
        return 0
    fi

    if [ -n "$off" ]; then
        r=$(api_post torrents/filePrio "hash=$h&id=$off&priority=0")
        case "$r" in *200*) ;; *) log "не вышло выключить [$off]: $r"; return 1 ;; esac
    fi
    r=$(api_post torrents/filePrio "hash=$h&id=$target&priority=1")
    case "$r" in
        *200*) log "качаем файл $((target+1)) из $total, остальные выключены" ;;
        *)     log "не вышло включить файл $((target+1)): $r" ;;
    esac

    # Раздачу нужно завести заново. Когда единственная включённая серия докачана,
    # качалка считает раздачу завершённой и тут же останавливает её по правилу
    # «рейтинг раздачи 0» — а включение следующей серии само по себе её не будит.
    # В ночь на 10.09 из-за этого закачка простояла 130 минут против 107 рабочих:
    # каждую серию будил сторож, и только через свои пятнадцать минут застоя.
    api_post torrents/start "hashes=$h" >/dev/null 2>&1
}

[ "$DRY" = 1 ] && { for h in $(all_hashes); do queue_one "$h"; done; exit 0; }

# Один проход и выход. Так скрипт зовёт хук завершения: сначала докачанная серия
# переводится в «не качать», и только потом раскладка уносит файл — иначе качалка
# хватится пропавшего файла и перекачает его заново (так мы однажды получили
# 17 ГБ дублей).
[ "${FQ_ONCE:-0}" = 1 ] && { for h in $(all_hashes); do queue_one "$h"; done; exit 0; }

log "очередь по одному файлу запущена"
while :; do
    for h in $(all_hashes); do queue_one "$h"; done
    sleep "$SLEEP"
done
