#!/system/bin/sh
# Отдаём видео на телевизор как есть, без «улучшений» приставки.
#
# Amlogic по умолчанию включает три обработчика поверх картинки:
#   ai_pq   — распознаёт сцену (лицо/трава/небо) и подкручивает под неё цвет и резкость
#   aisr    — дорисовывает резкость нейросетью при масштабировании
#   vsr     — второй блок «супер-разрешения» в тракте vpp
# Плюс блок постобработки VPP (резкость, динамический контраст, расширение чёрного,
# менеджер цвета). Режим pc_mode=1 — штатный обход всего этого, ровно то, что
# производители называют «режим ПК»: пиксель проходит насквозь.
#
# Значения живут в памяти драйвера и слетают при перезагрузке, а иногда и при
# переподключении HDMI (переключили вход телевизора — драйвер перечитал EDID и
# восстановил заводское). Поэтому раз в минуту тихо проверяем и возвращаем своё.

LOG=/data/local/tmp/aria2/videoraw.log

set_node() {          # set_node <файл> <значение> <что грепать для проверки>
  [ -e "$1" ] || return 0
  cur=$(cat "$1" 2>/dev/null)
  case "$cur" in
    *"$3"*) return 0 ;;                       # уже как надо
  esac
  echo "$2" > "$1" 2>/dev/null
  echo "$(date '+%F %T') $1: '$cur' -> '$2'" >> "$LOG"
}

apply() {
  set_node /sys/class/video/ai_pq_policy   0 ':0'
  set_node /sys/class/video/ai_pq_disable  1 ':1'
  set_node /sys/class/video/aisr_en        0 ':0'
  set_node /sys/class/video/vsr_top        0 ':0'
  # pc_mode только пишется, прочитать его нельзя — ставим при каждом проходе
  [ -e /sys/class/amvecm/pc_mode ] && echo 1 > /sys/class/amvecm/pc_mode 2>/dev/null
}

# ждём, пока драйверы поднимут свои узлы
i=0
while [ ! -e /sys/class/video/ai_pq_policy ] && [ $i -lt 30 ]; do
  sleep 2
  i=$((i+1))
done

echo "$(date '+%F %T') старт" >> "$LOG"
while true; do
  apply
  sleep 60
done
