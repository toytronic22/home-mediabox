# остановки на время просмотра недостаточно — вечером закачка стоит заранее.
# Останавливаем только то, что шло, и запоминаем в $HELD, чтобы потом вернуть ровно это:
# раздачи, остановленные руками, остаются стоять.
# Тихие часы ВЫКЛЮЧЕНЫ 14.09.2026 по решению хозяина. Их ставили, когда думали, что диску
# мешают закачки. Трёхчасовой прогон показал другое: диск деградирует от самой длительности
# непрерывного ЧТЕНИЯ (задержка 5,6 мс в первый час → 39,5 мс к третьему), при полностью
# остановленных закачках и ровной температуре. Значит запрещать закачки по расписанию незачем —
# достаточно закрывать качалку на время просмотра, что сторож и делает. Правило теперь простое:
# приставка включена и никто не смотрит кино — качаем.
# Чтобы вернуть тихие часы, достаточно снова развести эти два числа.
QUIET_FROM=0
QUIET_TO=0      # QUIET_FROM = QUIET_TO означает «тихих часов нет»
HELD=/data/local/tmp/aria2/.held

# Во время просмотра гасим качалку целиком, а не только раздачи (решено 14.09.2026).
# Зачем сильнее, чем пауза: остановленная качалка всё равно держала 350-650 МБ памяти под свой
# дисковый кэш и периодически трогала диск (сохранение .fastresume, ротация логов, служебные
# проходы libtorrent). А памяти в обрез: при буфере Kodi на 2048 МБ свободной оставалось 189 МБ —
# на таком остатке Android начинает отстреливать процессы, включая сам сторож.
# Гасим ТОЛЬКО штатно (init посылает SIGTERM, wait-mount.sh делает exec — сигнал доходит до
# качалки, и она успевает сохранить состояние). Добивать НЕЛЬЗЯ: после kill -9 она при следующем
# запуске перепроверяет все раздачи, а это часы чтения 583 ГБ на этом диске.
STOP_QBT_ON_WATCH=1
QBT_WAIT=30          # сколько секунд ждём штатного завершения, прежде чем махнуть рукой
QBT_HELD=0           # 1 = качалку погасили мы, её молчание — не авария
# Поднимаем качалку не сразу: иначе она будет дёргаться туда-сюда каждый раз, когда фильм
# ставят на паузу и отходят на пять минут. Ждём столько спокойных секунд подряд.
QBT_RESUME_DELAY=1200          # 20 минут
QBT_RESUME_AT=/data/local/tmp/aria2/.qbt-resume-at
# Аварийный режим, когда винчестер всё равно не поспевает.
SLOW_LIMIT=4M;  SLOW_JOBS=1; SLOW_PEERS=15
CHOKE_LOAD=12   # загрузка выше — диск захлёбывается. 10.09.2026 порог снижен с 35
                # до 12: те 35 были подобраны под exFAT, где качалка сама держала
                # загрузку около 12 из-за обнуления файлов. На ext4 обнуления нет,
                # и при 13 МБ/с загрузка всего 2.5 — значит 35 система бы не увидела
                # до самой беды. Двенадцать — это впятеро выше рабочей.
                # переезда на qBittorrent: у неё пул дисковых потоков, и десяток из
                # них штатно ждёт винчестер, поэтому рабочая загрузка ~12, а не 2-4
                # как у однопоточной арии. В ночь падения 08.09 было 88.
CHOKE_MEM=900   # свободной памяти меньше, МБ (норма 2200+, в ночь падения 510).
                # Это признак понадёжнее загрузки: он одинаков для любой качалки.
SLOW_HOLD_TICKS=10  # столько проходов держим аварийный режим после того, как отпустило
CHOKE_HARD=10       # столько проходов подряд терпим беду, прежде чем перезагрузиться

