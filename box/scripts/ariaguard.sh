#!/system/bin/sh
# Сторож приставки: следит за тем, что ломается само, и чинит без человека.
#
# Проверяет шесть вещей, каждую своим счётчиком, реагирует только на устойчивую
# картину (несколько проверок подряд), чтобы не дёргать службы из-за секундного
# всплеска нагрузки:
#
#  1) Качалка. aria2c однопоточный: когда диск уходит в потолок (торренты пишут
#     вразнобой, HDD от этого проседает с 78 до ~20 МБ/с), главный цикл застревает
#     на записи и перестаёт принимать входящие соединения. Ядро складывает их в
#     очередь порта — снаружи это выглядит как «ария отвалилась»: страница открыта,
#     а данные не идут. Само не рассасывается, лечится перезапуском.
#  2) Винчестер. Он на USB и от просадки питания умеет отваливаться на ходу.
#     Если это случилось, качать некуда: ставим закачки на паузу, чтобы ария не
#     писала в пустоту и не билась о несуществующие файлы.
#  3) Вебморды (ария и файлы). Их процессы могут жить, а сокет не отвечать.
#  4) Сеть. Приставка на Wi-Fi, а драйвер у неё капризный: соединение отваливается,
#     система при этом жива. Сама она не всегда возвращается — помогаем.
#  5) Режим качалки. Он зависит от двух вещей — идёт ли просмотр и чем приставка
#     подключена, — и выбирается по самому строгому из условий.
#     Про подключение. Замеры за двое суток: по кабелю с торрентами приставка живёт
#     часами, по Wi-Fi с торрентами — в среднем 18 минут до паники ядра, а по Wi-Fi
#     без закачек прожила 8 часов подряд. Значит, ядро роняет не Wi-Fi сам по себе,
#     а поток торрент-трафика через него. Поэтому на Wi-Fi качалку придерживаем, а
#     на кабеле отпускаем на полную.
#     Про просмотр. Кино приставка играет сама, файлы читает со своего винчестера,
#     а тот отдаёт 55-66 МБ/с даже под торрентами при нужных 4K-ремуксу 10-15 — за
#     диск волноваться не о чем. Волноваться надо за интернет: торренты забирают
#     110 Мбит из 118, и всё, что идёт онлайн (Лампа, TizenTube), захлёбывается.
#     Поэтому на время просмотра качалку придерживаем сильнее всего.
#     Смотрят или нет, узнаём так: если HDMI не подключён — смотреть физически
#     нечем и дальше проверять нечего; иначе спрашиваем Kodi напрямую, а Лампу и
#     TizenTube выдаёт то, что кто-то держит звук или играет им.
#  6) Остатки удалённых закачек. aria2 удалять файлы не умеет в принципе — ни сам,
#     ни через вебморду. Убрал задачу в AriaNg — папка на сотню гигабайт остаётся
#     висеть на диске. Раз в пять минут сверяем папки со списком живых задач и
#     убираем то, за чем задачи больше нет.
#
# Перезагрузку после паники ядра сторож не делает: приставка поднимается сама,
# а всё наше хозяйство прописано в автозапуск.

