    kodi_playing && return 0
    snd=$(dumpsys audio 2>/dev/null)
    echo "$snd" | sed -n '/Audio Focus stack entries/,/^ *$/p' | grep -q 'clientId' && return 0
    # TizenTube играет, не забирая фокус звука, — его выдаёт только запущенный плеер.
    echo "$snd" | grep -q 'AudioPlaybackConfiguration piid:.*state:started.*usage=USAGE_MEDIA'
}

# Ограничения: потолок скорости, сколько задач качать разом, сколько соединений
# держать на задачу. Скорость качалка принимает в байтах в секунду, 0 — без предела.
set_limits() {
    case "$1" in
        0) bytes=0 ;;
        *) # awk, а не $(( )): нужно дробное «27.5M» (=220 Мбит), плюс в оболочке
           #      приставки арифметика 32-битная и на сотнях мегабайт врёт.
           bytes=$(printf '%s' "$1" | tr -dc '0-9.' | awk '{printf "%d", $1*1048576}') ;;
    esac
    api_post transfer/setDownloadLimit "limit=$bytes" >/dev/null 2>&1
    api_post app/setPreferences \
        "json=%7B%22max_active_downloads%22%3A$2%2C%22max_active_torrents%22%3A$2%2C%22max_connec_per_torrent%22%3A$3%7D" \
      | grep -q '200 OK'
}

# --- уборка остатков удалённых закачек -----------------------------------------
# Зачем: aria2 удалять файлы не умеет в принципе — ни сам, ни через вебморду.
# Убрал задачу в AriaNg — папка на сотню гигабайт остаётся висеть на диске, и
# заметить это можно только вручную. Поэтому раз в пять минут сверяем папки в
# Download со списком живых задач и убираем то, за чем задачи больше нет.
#
# Осторожность важнее скорости. 08.09.2026 эта уборка снесла 12 ГБ живой раздачи
# и .torrent работающей задачи: список живых задач собирался двумя отдельными
# запросами, и когда один из них промолчал (а качалка в тот момент перезапускалась),
# неполный список превратил живые папки в «остатки». Отсюда правила:
#   * снимок задач берём одним заходом по ВСЕМ трём спискам — активные, ожидающие
#     и остановленные; не пришёл хотя бы один ответ — уборки в этом проходе нет
#     (счётчики при этом не трогаем: подозрение возникает только из полного снимка,
#     а сброс ломал уборку — качалка на внешнем диске отвечает через раз);
#   * задач ноль — не делаем ничего (так выглядит и только что запущенная ария);
#   * папка должна оказаться лишней ЧЕТЫРЕ прохода подряд (это ≥20 минут) —
#     перезапуск качалки с восстановлением магнет-метаданных столько не длится;
#   * ничего свежее получаса не трогаем: в такую папку могли только что писать;
#   * за один проход убираем не больше одной папки — если правило всё же ошибётся,
#     цена ошибки будет одна папка, а не весь Download;
#   * .torrent сверяем с хешами из того же снимка, а НЕ с файлом сессии: сессия
#     пишется раз в 30 секунд и после перезапуска пуста — именно на этом
#     был потерян торрент живой задачи;
#   * трогаем только Download: медиатека и резервные копии не наш огород.

DLDIR=$HDD/Download
STATE=$BIN/orphans.state

SNAP=$BIN/.orphans.snap
KEEP_MIN=30          # моложе этого (в минутах) не трогаем ничего
NEED_MISSES=4        # столько проходов подряд папка должна выглядеть лишней

# Менялось ли что-нибудь внутри за последние KEEP_MIN минут. Ключ -mmin выбран
# намеренно: -newermt toybox не понимает и молча ничего не находит, то есть проверка
# выглядела бы рабочей, а на деле всегда пропускала бы свежие файлы.
touched_recently() {
    [ -n "$(find "$1" -mmin "-$KEEP_MIN" 2>/dev/null | head -1)" ]
}

# Снимок всех задач одним запросом: эта качалка отдаёт список целиком, вместе с
# приостановленными и завершёнными. Делить на три вызова и ловить полуответы,
# как приходилось с арией, больше не нужно — но пустой ответ по-прежнему повод
# уборку пропустить.
tasks_snapshot() {
    : > "$SNAP"
    out=$(api "torrents/info")
    case "$out" in
        *'"hash"'*) printf '%s\n' "$out" > "$SNAP"; return 0 ;;
        *'[]'*)     printf '[]\n'   > "$SNAP"; return 0 ;;
        *)          return 1 ;;
    esac
}

# Последовательная загрузка — главное, ради чего мы ушли с арии: на этом диске она
# втрое дешевле по вводу-выводу (замер 09.09.2026: 5 мс ожидания на мегабайт против
# 49). Качалка включает её только тем задачам, что добавили с этим флагом, а ловец
# магнетов о нём не знает — поэтому дописываем флаг сами. Список задач разбираем,
# разрезая JSON по границам объектов: полноценного разбора здесь всё равно нет.
ensure_sequential() {
    [ -s "$SNAP" ] || return 0
    sed 's/},{/}\n{/g' "$SNAP" | while IFS= read -r obj; do
        case "$obj" in *'"seq_dl":false'*) ;; *) continue ;; esac
        h=$(printf '%s' "$obj" | grep -oE '"hash":"[0-9a-f]{40}"' | cut -d'"' -f4)
        [ -z "$h" ] && continue
        n=$(printf '%s' "$obj" | grep -oE '"name":"[^"]+"' | cut -d'"' -f4)
        api_post torrents/toggleSequentialDownload "hashes=$h" >/dev/null 2>&1
        log "включил последовательную загрузку: ${n:-$h}"
    done
}

# Нужен ли файл метаданных. Имя .torrent — хеш той редакции раздачи, что скачали
# с трекера, и с хешем задачи он совпадает не всегда (у магнет-задач — почти
# никогда). Поэтому главный признак — имя раздачи внутри bencode, как в medialib.sh.
torrent_needed() {
    h=$(printf '%s' "${1%.torrent}" | tr 'A-Z' 'a-z')
    printf '%s\n' "$hashes" | grep -qxF "$h" && return 0
    printf '%s\n' "$live" > "$SNAP.names"
    while IFS= read -r n; do
        [ -z "$n" ] && continue
        if grep -aqF "$n" "$1"; then rm -f "$SNAP.names"; return 0; fi
    done < "$SNAP.names"
    rm -f "$SNAP.names"
    return 1
}

tidy_orphans() {
    [ -d "$DLDIR" ] || return 0
    [ -s "$SNAP" ] || return 0

    # Имена живых папок берём ДВУМЯ способами и объединяем.
    #
    # 09.09.2026 это стоило удалённой папки на 96 ГБ. Раздачу добавили магнетом, и
    # качалка взяла имя из параметра dn= ссылки — «Ukrytie-Bunker-Silo-S02-2024-...»,
    # тогда как папка внутри торрента называется «Silo.S02.2160p.ATVP.WEB-DL...».
    # Сторож сравнивал папку с именем задачи, совпадения не находил и через четыре
    # прохода снёс живые данные. Через ловец магнетов так будет каждый раз.
    #
    # Поэтому главный источник — content_path: это фактический путь к содержимому,
    # он не врёт никогда. Имя задачи оставлено вторым источником: для однофайловых
    # раздач content_path указывает на сам файл, а не на папку.
    live=$( { tr ',' '\n' < "$SNAP" | grep -oE '"content_path":"[^"]+"' | cut -d'"' -f4 \
                | sed 's|\\/|/|g' | sed 's|^.*/Download/||' | sed 's|/.*||'
              tr ',' '\n' < "$SNAP" | grep -oE '"name":"[^"]+"' | cut -d'"' -f4
            } | grep -v '^$' | sort -u )
    hashes=$(tr ',' '\n' < "$SNAP" | grep -oE '"hash":"[0-9a-fA-F]+"' | cut -d'"' -f4 | tr 'A-Z' 'a-z' | sort -u)
    if [ -z "$live" ] && [ -z "$hashes" ]; then
        : > "$STATE"
        return 0
    fi

    cd "$DLDIR" 2>/dev/null || return 0
    fresh=""
    removed=0
    for d in */; do
        [ "$d" = "*/" ] && break
        name="${d%/}"
        printf '%s\n' "$live" | grep -qxF "$name" && continue
        # в папку могли только что писать — свежую не трогаем даже как кандидата
        touched_recently "$name" && continue

        n=$(awk -F'\t' -v k="$name" '$2==k {print $1; exit}' "$STATE" 2>/dev/null)
        [ -z "$n" ] && n=0
        n=$((n + 1))
        if [ "$n" -ge "$NEED_MISSES" ] && [ "$removed" -eq 0 ]; then
            sz=$(du -sk "$name" 2>/dev/null | cut -f1)
            rm -rf -- "$DLDIR/$name"   # абсолютным путём: скрипт может снести десятки гигабайт && rm -f -- "$name.aria2"
            removed=1
            log "убрал остаток удалённой закачки: $name ($((${sz:-0} / 1048576)) ГБ)"
        else
            fresh="$fresh$n	$name
"
        fi
    done

    # Файлы метаданных: лишние — те, в которых не упомянута ни одна живая раздача.
    # Счётчик и порог те же, что для папок.
    for t in *.torrent; do
        [ "$t" = "*.torrent" ] && break
        torrent_needed "$t" && continue
        touched_recently "$t" && continue
        n=$(awk -F'\t' -v k="$t" '$2==k {print $1; exit}' "$STATE" 2>/dev/null)
        [ -z "$n" ] && n=0
        n=$((n + 1))
        if [ "$n" -ge "$NEED_MISSES" ]; then
            rm -f -- "$t" && log "убрал лишний файл метаданных: $t"
        else
            fresh="$fresh$n	$t
"
        fi
    done

    printf '%s' "$fresh" > "$STATE"
}

TS_CACHE=/data/local/tmp/torrserver/cache

ts_open() {
    out=$( { printf 'POST /torrents HTTP/1.0\r\nContent-Type: application/json\r\nContent-Length: 17\r\n\r\n{"action":"list"}'; sleep 2; } \
        | timeout 15 nc 127.0.0.1 8091 2>/dev/null | tail -1 )
    case "$out" in '['*) ;; *) return 1 ;; esac
    printf '%s' "$out" | grep -oE '"hash":"[0-9a-f]{40}"|"stat":[0-9]+' \
        | awk -F'"' '$2 == "hash" {h = $4; next} h != "" && $3 ~ /^:[0-3]$/ {print h} {h = ""}'
}

tidy_ts_cache() {
    [ -d "$TS_CACHE" ] || return 0
    for d in "$TS_CACHE"/*/; do
        [ -d "$d" ] || continue
        h=$(basename "$d")
        case "$h" in *[!0-9a-f]*) continue ;; esac
        [ "${#h}" -eq 40 ] || continue
        touched_recently "$d" && continue
        open=$(ts_open) || return 0
        printf '%s\n' "$open" | grep -qxF "$h" && continue
        sz=$(du -sk "$d" 2>/dev/null | cut -f1)
        rm -rf -- "$TS_CACHE/$h"
        log "убрал остаток кэша TorrServer: $h ($((${sz:-0} / 1024)) МБ)"
    done
}

log "сторож запущен"

while :; do
    IS_WATCHING=0; watching && IS_WATCHING=1
    DISK_BAD=0; disk_evidence && DISK_BAD=1
    # Качалку могли поднять руками (кнопка в файловом менеджере) — согласуемся с реальностью,
    # иначе сторож и дальше считал бы её молчащей по нашей воле и не присматривал бы за ней.
    if [ "$QBT_HELD" = 1 ] && pidof qbittorrent-nox >/dev/null 2>&1; then
        QBT_HELD=0; rm -f "$QBT_RESUME_AT"
        log "качалку подняли вручную — снимаю свой присмотр"
    fi
    sleep 60
    rotate_log

    # 1. Качалка ---------------------------------------------------------------
    q=$(queue_len); [ -z "$q" ] && q=0
    if [ "$QBT_HELD" = 1 ]; then
        # мы сами её погасили на время просмотра — молчание ожидаемо, сторожить нечего
        BAD_ARIA=0; BAD_IO=0
    elif rpc_ok && [ "$q" -lt 6 ]; then
        [ "$BAD_ARIA" -gt 0 ] && log "качалка отпустила сама (очередь $q)"
        BAD_ARIA=0; BAD_IO=0
    elif on_disk_io; then
        # Состояние D — процесс ждёт винчестер, а не завис: три торрента на внешний
        # диск через exFAT дают паузы, в которые RPC отвечает через раз. Перезапуск
        # тут только вредит: теряется до полминуты прогресса, а пока качалка
        # поднимается, её задачи не видны — на этом 08.09.2026 уборка снесла живую
        # раздачу. Ждём, но не бесконечно.
        BAD_IO=$((BAD_IO + 1))
        [ "$BAD_IO" = 1 ] && log "качалка ждёт винчестер (состояние D) — не трогаю"
        if [ "$BAD_IO" -ge 20 ]; then
            log "качалка висит на винчестере 20 минут — всё же перезапускаю"
            restart qbt; sleep 20; BAD_IO=0; BAD_ARIA=0
        fi
    else
        BAD_IO=0
        BAD_ARIA=$((BAD_ARIA + 1))
        log "качалка не отвечает: очередь=$q, попытка $BAD_ARIA из 5"
        if [ "$BAD_ARIA" -ge 5 ]; then
            restart qbt
            sleep 20
            rpc_ok && log "качалка поднялась" || log "качалка молчит и после перезапуска — нужен человек"
            BAD_ARIA=0
        fi
    fi

    # 2. Винчестер -------------------------------------------------------------
    if disk_ok; then
        if [ "$DISK_WARNED" = "1" ]; then
            log "винчестер вернулся, снимаю паузу"
            api_post torrents/start "hashes=all" >/dev/null 2>&1
            DISK_WARNED=0
        fi
    elif [ "$DISK_WARNED" = "0" ]; then
        log "ВИНЧЕСТЕР ПРОПАЛ — ставлю закачки на паузу"
        api_post torrents/stop  "hashes=all" >/dev/null 2>&1
        DISK_WARNED=1
    fi

    # 3. Вебморды --------------------------------------------------------------
    # Пока качалку погасили мы (идёт просмотр), её вебморда молчит по делу — это не авария.
    # Без этой оговорки сторож через три прохода полез бы её «чинить» и поднял бы качалку
    # обратно посреди фильма, то есть отменил бы собственное решение.
    if [ "$QBT_HELD" = 1 ]; then
        web_ok 8777 && BAD_WEB=0
    elif web_ok 8080 && web_ok 8777; then
        BAD_WEB=0
    else
        BAD_WEB=$((BAD_WEB + 1))
        log "вебморда не отвечает, попытка $BAD_WEB из 3"
        if [ "$BAD_WEB" -ge 3 ]; then
            # На 8080 с 09.09.2026 сидит qBittorrent, а не старая вебморда AriaNg. Раньше здесь
            # стоял `restart ariangweb` — и если бы вебморда качалки промолчала три прохода подряд,
            # сторож поднял бы на её порту файловый сервер, качалка не смогла бы его занять, и
            # приставка осталась бы без закачек до человека. Дважды доходило до второй попытки.
            web_ok 8080 || restart qbt
            web_ok 8777 || restart fileweb
            BAD_WEB=0
        fi
    fi

    # 5. Режим качалки: смотрят / кабель / Wi-Fi -------------------------------
    # Просмотр важнее всего: он задаёт самый щадящий режим независимо от того,
    # чем приставка подключена.
    # Аварийный режим держим ещё десять проходов после того, как отпустило, иначе
    # сторож заметался бы между режимами: сбавил — полегчало — разогнал — снова встал.
    # Второй слой самолечения. Первый — аварийный режим ниже: сбавить обороты и
    # переждать. Если и через десять минут не отпустило, сбавлять уже поздно:
    # уходим на перезагрузку сами, пока процессы ещё шевелятся. Третий слой —
    # ядерный детектор зависших задач (hung_task_panic в aria2.rc): он поднимет
    # приставку, даже когда сюда управление уже не вернётся, но только через
    # десять минут полного паралича.
    if disk_choking; then
        CHOKING=$((CHOKING + 1))
        if [ "$CHOKING" -ge "$CHOKE_HARD" ]; then
            if [ "$IS_WATCHING" = 1 ]; then
                log "винчестер не поспевает $CHOKE_HARD минут подряд (занят ${DISK_BUSY}%, грязных ${DISK_DIRTY} МБ), но идёт просмотр — перезагрузку не делаю, жду"
                CHOKING=$((CHOKE_HARD - 1))
            else
            log "винчестер не поспевает $CHOKE_HARD минут подряд (занят ${DISK_BUSY}%, грязных ${DISK_DIRTY} МБ), аварийный режим не помог — перезагружаюсь"
            sync
            reboot
            fi
            sleep 30
        fi
    else
        CHOKING=0
    fi

    if disk_choking; then
        [ "$SLOW_HOLD" -eq 0 ] && log "винчестер не поспевает (загрузка $(cut -d' ' -f1 /proc/loadavg), свободно $(awk '/^MemAvailable:/ {printf "%d", $2/1024; exit}' /proc/meminfo) МБ) — сбавляю обороты"
        SLOW_HOLD=$SLOW_HOLD_TICKS
    elif [ "$SLOW_HOLD" -gt 0 ]; then
        SLOW_HOLD=$((SLOW_HOLD - 1))
    fi

    # --- пауза закачки: просмотр или тихие часы ---------------------------------
    if [ "$IS_WATCHING" = 1 ]; then hold_why="просмотр"
    elif quiet_hours; then hold_why="тихие часы $QUIET_FROM:00-$QUIET_TO:00"
    else hold_why=""; fi
    # LAST_HOLD пишем ДО разбора: раньше присваивание стояло ниже чтения, и на первом проходе
    # в журнал всегда попадало слово «пауза» вместо настоящей причины.
    [ -n "$hold_why" ] && LAST_HOLD=$hold_why
    if [ -n "$hold_why" ]; then
        # каждый проход: вдруг что-то запустили руками или очередью — тоже останавливаем
        hold_downloads "$hold_why"
    elif [ -f "$HELD" ] && pidof qbittorrent-nox >/dev/null 2>&1; then
        # Снимать паузу можно только с живой качалкой. Она закрывается на время фильма и
        # поднимается лишь через 20 спокойных минут, а список отложенных раздач стирается сразу
        # после попытки — без этой проверки раздачи остались бы на паузе навсегда.
        release_downloads "${LAST_HOLD:-пауза}"
    fi
    # Качалку целиком гасим только на время просмотра. В тихие часы она остаётся жить:
    # раздачи и так на паузе, а вебморда должна быть доступна, чтобы добавить торрент вечером.
    if [ "$IS_WATCHING" = 1 ]; then qbt_service_hold; else qbt_service_resume; fi


    if [ "$IS_WATCHING" = 1 ]; then want=view
    elif [ "$SLOW_HOLD" -gt 0 ]; then want=slow
    elif on_wire;  then        want=wire
    else                       want=wifi
    fi

    if [ "$want" != "$MODE" ]; then
        case "$want" in
            view) set_limits "$VIEW_LIMIT" "$VIEW_JOBS" "$VIEW_PEERS" \
                    && { log "идёт просмотр — придерживаю качалку до $VIEW_LIMIT"; MODE=view; } ;;
            slow) set_limits "$SLOW_LIMIT" "$SLOW_JOBS" "$SLOW_PEERS" \
                    && { log "аварийный режим: $SLOW_LIMIT, задач $SLOW_JOBS — жду, пока винчестер разгребёт"; MODE=slow; } ;;
            wire) set_limits "$WIRE_LIMIT" "$WIRE_JOBS" "$WIRE_PEERS" \
                    && { log "кабель, никто не смотрит — потолок $WIRE_LIMIT (задач $WIRE_JOBS, пиров $WIRE_PEERS)"; MODE=wire; } ;;
            wifi) # Энергосбережение Wi-Fi гасим здесь. Раньше это делал отдельный скрипт
                  # wifiwatch, удалённый 14.09.2026 как мёртвый: приставка давно на кабеле.
                  # Но это был антипаник-костыль для драйвера Broadcom, и терять его нельзя —
                  # при возврате на Wi-Fi про него бы никто не вспомнил.
                  /system/bin/iw dev wlan0 get power_save 2>/dev/null | grep -q off \
                    || /system/bin/iw dev wlan0 set power_save off 2>/dev/null
                  set_limits "$WIFI_LIMIT" "$WIFI_JOBS" "$WIFI_PEERS" \
                    && { log "работаем по Wi-Fi — придерживаю качалку ($WIFI_LIMIT, задач $WIFI_JOBS, пиров $WIFI_PEERS)"; MODE=wifi; } ;;
        esac
    fi

    # 6. Задачи: снимок, последовательная загрузка, уборка остатков -------------
    # Снимок нужен и тому и другому, поэтому берём его каждый проход — он лёгкий,
    # пара килобайт. Не пришёл — просто пропускаем оба дела до следующего раза.
    TICK=$((TICK + 1))
    if tasks_snapshot; then
        SNAP_MISSED=0
        ensure_sequential

        # Очередь «по одной серии» заводилась только хуком завершения раздачи, поэтому на только
        # что добавленных раздачах не запускалась вовсе: 14.09.2026 все восемь серий сезона
        # качались вперемешку. Дёргаем её раз в десять проходов — этого хватает, чтобы подхватить
        # новое, и не нагружает качалку опросом файлов каждую минуту.
        FQ_TICK=$(( ${FQ_TICK:-0} + 1 ))
        if [ "$FQ_TICK" -ge 10 ]; then
            FQ_TICK=0
            qbt_alive && FQ_ONCE=1 sh "$BIN/filequeue.sh" >/dev/null 2>&1
        fi
        [ $((TICK % 5)) -eq 0 ] && tidy_orphans
    else
        # Молчание погашенной нами качалки — ожидаемо, в журнал не пишем.
        [ "$SNAP_MISSED" = 0 ] && [ "$QBT_HELD" != 1 ] && log "качалка не отдала список задач — уборку пропускаю"
        SNAP_MISSED=$((SNAP_MISSED + 1))
    fi
    [ $((TICK % 5)) -eq 0 ] && tidy_ts_cache

    # 4. Сеть ------------------------------------------------------------------
    if net_ok; then
        [ "$BAD_NET" -gt 0 ] && log "сеть вернулась сама"
        BAD_NET=0
    else
        BAD_NET=$((BAD_NET + 1))
        log "роутер не отвечает, попытка $BAD_NET из 5"
        if [ "$BAD_NET" -ge 5 ]; then
            log "перезапускаю Wi-Fi"
            cmd wifi set-wifi-enabled disabled >/dev/null 2>&1
            sleep 5
            cmd wifi set-wifi-enabled enabled >/dev/null 2>&1
            sleep 25
            net_ok && log "сеть поднялась" || log "сеть не поднялась — нужен человек"
            BAD_NET=0
        fi
    fi
done
