# curl на приставке нет, запросы собираем руками через nc. Важная тонкость:
# здешний nc закрывает соединение целиком, как только кончился stdin, и медленный
# собеседник не успевает ответить — вебморда файлов так «молчала» на каждый запрос.
# Поэтому после запроса держим ввод открытым паузой.
# ВАЖНО про имена ручек: в qBittorrent 5.x пауза и снятие паузы называются
# stop/start, а прежние pause/resume отвечают 404. Проверено 09.09.2026 — из-за
# них пауза при пропаже винчестера молча не срабатывала.
# Запрос к API качалки. Своя подсеть у неё в доверенных, поэтому пароль не нужен.
# Пауза перед закрытием — та же уловка, что и раньше: nc на Android рвёт соединение
# по концу stdin, и медленный собеседник не успевает ответить.
# Переходники: имена в этом скрипте исторические, тела — из общего файла.
api()        { qbt_get "$1"; }
api_post()   { qbt_post "$1" "$2"; }
rpc_ok()     { qbt_ok; }
disk_ok()    { disk_ready; }
rotate_log() { rotate_one "$LOG" 204800 600; }

queue_len(){ ss -tln 2>/dev/null | awk '$4 ~ /:8080$/ {print $2; exit}'; }

web_ok()   { { printf 'GET / HTTP/1.0\r\n\r\n'; sleep 3; } \
                 | timeout 12 nc 127.0.0.1 "$1" 2>/dev/null | grep -q 'HTTP/1'; }
# Не поспевает ли винчестер за закачкой. Смотрим не на сам диск, а на его следы
# в системе: очередь процессов и остаток памяти. Грязные страницы, которые некуда
# сбросить, съедают память и загоняют загрузку в десятки — именно так приставка
# и умерла в ночь на 09.09.2026, за девять минут от нормы до паралича.
# Признаки самого диска: грязных страниц ≥64 МБ или устройство занято ≥50 % времени
# с прошлого прохода. Считается один раз за проход (в начале цикла → DISK_BAD).
disk_evidence() {
    d=$(awk '/^Dirty:/ {printf "%d", $2/1024; exit}' /proc/meminfo)
    t=$(awk '{print $10}' /sys/block/sda/stat 2>/dev/null); now=$(date +%s)
    busy=0
    if [ -n "$t" ] && [ -n "$PREV_TICKS" ] && [ "$now" -gt "${PREV_TS:-0}" ]; then
        busy=$(awk -v a="$PREV_TICKS" -v b="$t" -v s=$((now - PREV_TS)) 'BEGIN{printf "%d", (b-a)/(s*10)}')
    fi
    PREV_TICKS=$t; PREV_TS=$now
    DISK_BUSY=$busy; DISK_DIRTY=${d:-0}
    [ "${d:-0}" -ge 64 ] || [ "$busy" -ge 50 ]
}
# Диск захлёбывается — только если тревогу памяти/загрузки подтверждает сам диск.
# 11.09.2026 сторож ушёл в аварийный режим при простаивающем диске: приложения и Kodi съели
# память до 891 МБ при пороге 900, грязных страниц было 4 КБ — и через десять проходов
# он перезагрузил бы приставку посреди фильма. Память и загрузка — сигнал, диск — подтверждение.
disk_choking() {
    la=$(cut -d' ' -f1 /proc/loadavg | cut -d. -f1)
    av=$(awk '/^MemAvailable:/ {printf "%d", $2/1024; exit}' /proc/meminfo)
    signal=0
    [ -n "$la" ] && [ "$la" -ge "$CHOKE_LOAD" ] && signal=1
    [ -n "$av" ] && [ "$av" -lt "$CHOKE_MEM" ] && signal=1
    [ "$signal" = 1 ] && [ "${DISK_BAD:-0}" = 1 ]
}

# Ждёт ли качалка винчестер: состояние D в /proc — непрерываемый сон на вводе-выводе.
on_disk_io() {
    for p in $(pidof qbittorrent-nox 2>/dev/null); do
        case "$(cut -d' ' -f3 "/proc/$p/stat" 2>/dev/null)" in D*) return 0 ;; esac
    done
    return 1
}
net_ok()   { ping -c 1 -W 3 "$ROUTER" >/dev/null 2>&1; }

# Вежливой просьбы мало. Ради чего это писалось: качалка залипает именно тогда,
# когда застряла на записи на диск, — в этом состоянии она не отвечает ни на что,
# init считает службу живой, а процесс продолжает держать порт 6800, и новая копия
# не поднимается. Поэтому после stop добиваем процесс принудительно (сначала CONT,
# чтобы разбудить остановленный, затем KILL) и только потом запускаем заново.
kill_hard() {
    for p in $(pidof "$1" 2>/dev/null); do
        kill -CONT "$p" 2>/dev/null
        kill -9 "$p" 2>/dev/null
    done
}

restart() {
    log "перезапускаю $1"
    stop "$1" 2>/dev/null
    sleep 4
    [ "$1" = "qbt" ] && kill_hard qbittorrent-nox
    sleep 2
    start "$1" 2>/dev/null
}

# Кабель считаем подключённым, если на eth0 есть адрес.
on_wire() { ip -o -4 addr show eth0 2>/dev/null | grep -q 'inet '; }

# Kodi отвечает на локальный запрос быстро и честно говорит, играет ли он.

# Смотрят ли кино прямо сейчас. Сначала самый дешёвый и надёжный признак: если
# HDMI не подключён, смотреть физически нечем — на этом можно и остановиться.
# Дальше спрашиваем Kodi, а для Лампы и TizenTube смотрим, держит ли кто-то звук.
quiet_hours() {
    [ "$QUIET_FROM" = "$QUIET_TO" ] && return 1
    h=$(date +%H); h=${h#0}; h=${h:-0}
    if [ "$QUIET_FROM" -lt "$QUIET_TO" ]; then
        [ "$h" -ge "$QUIET_FROM" ] && [ "$h" -lt "$QUIET_TO" ]
    else
        [ "$h" -ge "$QUIET_FROM" ] || [ "$h" -lt "$QUIET_TO" ]
    fi
}
# running = всё, что не остановлено (качает, раздаёт, стоит в очереди, ждёт пиров).
# Разбор только grep -o: sed с жадным .* на большом JSON у toybox зависает.
running_hashes() { api "torrents/info?filter=running" | grep -o '"hash":"[0-9a-f]*"' | cut -d'"' -f4; }
hold_downloads() {
    running_hashes > "$HELD.new"
    n=$(wc -l < "$HELD.new" | tr -d ' ')
    if [ "$n" -gt 0 ]; then
        api_post torrents/stop "hashes=$(tr '\n' '|' < "$HELD.new" | sed 's/|$//')" >/dev/null 2>&1
        cat "$HELD.new" >> "$HELD"
        log "закачка на паузе ($1): остановил $n раздач"
    else
        [ -f "$HELD" ] || : > "$HELD"
    fi
    rm -f "$HELD.new"
}
release_downloads() {
    if [ -s "$HELD" ]; then
        api_post torrents/start "hashes=$(sort -u "$HELD" | tr '\n' '|' | sed 's/|$//')" >/dev/null 2>&1
        log "пауза снята ($1): вернул $(sort -u "$HELD" | wc -l | tr -d ' ') раздач"
    fi
    rm -f "$HELD"
}

qbt_service_hold() {
    [ "$STOP_QBT_ON_WATCH" = 1 ] || return 0
    # Снова смотрят — отсчёт до подъёма отменяется. Стоит ДО проверки QBT_HELD: до 02.10.2026
    # стоял после неё и не срабатывал никогда, ведь отсчёт идёт как раз при погашенной качалке.
    # Из-за этого после перерыва между сериями качалка поднималась сразу, а не через 20 минут.
    rm -f "$QBT_RESUME_AT"
    [ "$QBT_HELD" = 1 ] && return 0
    qbt_alive || return 0
    log "идёт просмотр — глушу качалку целиком (было $(awk '/^MemAvailable:/{printf "%d", $2/1024}' /proc/meminfo) МБ свободно)"
    # Сперва дожидаемся, пока качалка запишет отметки о прогрессе: от сигнала она умирает
    # мгновенно, и всё скачанное с последнего периодического сохранения пришлось бы качать заново.
    qbt_flush_resume || log "качалка не записала отметки за 20 с — закрываю как есть"
    stop qbt 2>/dev/null
    i=0
    while qbt_alive && [ "$i" -lt "$QBT_WAIT" ]; do sleep 1; i=$((i + 1)); done
    if qbt_alive; then
        # Не добиваем: перепроверка раздач дороже, чем лишние 400 МБ занятой памяти.
        log "качалка не завершилась за ${QBT_WAIT} с — оставляю как есть, добивать нельзя (будет перепроверка)"
        start qbt 2>/dev/null
    else
        QBT_HELD=1
        log "качалка погашена за ${i} с, свободно стало $(awk '/^MemAvailable:/{printf "%d", $2/1024}' /proc/meminfo) МБ"
    fi
}
qbt_service_resume() {
    [ "$QBT_HELD" = 1 ] || return 0
    now=$(date +%s)
    if [ ! -s "$QBT_RESUME_AT" ]; then
        echo $((now + QBT_RESUME_DELAY)) > "$QBT_RESUME_AT"
        log "просмотр окончен — подниму качалку через $((QBT_RESUME_DELAY / 60)) мин, если кино не включат снова"
        return 0
    fi
    at=$(cat "$QBT_RESUME_AT" 2>/dev/null)
    case "$at" in ''|*[!0-9]*) at=$now ;; esac
    [ "$now" -lt "$at" ] && return 0
    rm -f "$QBT_RESUME_AT"
    QBT_HELD=0
    start qbt 2>/dev/null
    log "тихо $((QBT_RESUME_DELAY / 60)) мин — поднимаю качалку"
}

