#!/system/bin/sh
# Общие функции для всех сторожей приставки. Подключается строкой:
#     . /data/local/tmp/aria2/lib.sh
#
# Зачем собрано в одном месте. К 14.09.2026 обращение к качалке было скопировано в семь мест,
# и копии вели себя по-разному: где-то ответ обрезался до последней строки, где-то возвращался
# вместе с заголовками HTTP (из-за этого снимок раздач начинался с «HTTP/1.1 200 OK»), таймауты
# гуляли от 10 до 20 секунд. Работало по случайности — поиск по «"hash":» находил своё и в мусоре.
# Функция log() была скопирована в девять файлов слово в слово.
#
# Оболочка mksh + toybox: без bash-измов, без curl, без python, без jq.

LIB_BIN=/data/local/tmp/aria2
LIB_HDD=/mnt/media_rw/FA9E-9466      # имя точки — серийник старого exFAT-тома, менять нельзя:
                                     # по нему построены пути в базе медиатеки Kodi
LIB_QBT=127.0.0.1:8080               # вебморда качалки
LIB_KODI=127.0.0.1:8090              # Kodi (8080 занят качалкой)

# Запись в журнал. Путь берётся из $LOG вызывающего скрипта.
# Рядом со временем пишем аптайм: часы при загрузке не синхронизированы, и время в первых
# записях после включения врёт. По аптайму видно, к какой именно загрузке относится строка —
# без этого нельзя отличить «приставка перезагрузилась» от «просто прошло время».
log() { echo "$(date '+%F %T') [+$(cut -d. -f1 /proc/uptime)s] $*" >> "${LOG:-$LIB_BIN/common.log}"; }

# --- качалка -----------------------------------------------------------------
# nc на Android закрывает соединение, как только кончился stdin, и медленный собеседник не
# успевает ответить — отсюда пауза перед закрытием. `tail -1` отрезает заголовки HTTP: без него
# в ответе приезжает весь заголовочный блок, и любой греп по телу может поймать чужое.
qbt_get() {
    { printf 'GET /api/v2/%s HTTP/1.1\r\nHost: %s\r\nConnection: close\r\n\r\n' "$1" "$LIB_QBT"; sleep 2; } \
        | timeout 15 nc 127.0.0.1 8080 2>/dev/null | tail -1
}
qbt_post() {
    _b="$2"
    { printf 'POST /api/v2/%s HTTP/1.1\r\nHost: %s\r\nContent-Type: application/x-www-form-urlencoded\r\nContent-Length: %d\r\nConnection: close\r\n\r\n%s' \
        "$1" "$LIB_QBT" "${#_b}" "$_b"; sleep 2; } | timeout 15 nc 127.0.0.1 8080 2>/dev/null | head -1
}
qbt_alive() { pidof qbittorrent-nox >/dev/null 2>&1; }

# Просит качалку записать отметки о прогрессе и ДОЖИДАЕТСЯ записи. Звать перед каждым закрытием.
#
# Зачем ожидание. 14.09.2026 приставку перезагрузили кнопкой: качалку закрыли штатно, она умерла
# за доли секунды — и не успела сохранить .fastresume. После загрузки она восстановилась с
# последнего периодического сохранения (по умолчанию раз в час) и собралась перекачивать
# 1,6 ГБ, которые уже лежали на диске. Данные были целы, спасла принудительная перепроверка.
# Опыт показал: постановка раздач на паузу заставляет качалку сбросить отметки на диск за 2-6 с.
# Ждём, пока ВСЕ файлы отметок станут свежее момента, когда мы попросили паузу.
qbt_flush_resume() {
    _d=/data/local/tmp/qbt/profile/qBittorrent/data/BT_backup
    # Отметку считаем свежей, если она записана за последние две минуты, а не строго после нашей
    # просьбы. Сторож ставит раздачи на паузу ДО вызова этой функции — качалка сбрасывает отметки
    # там, и повторная просьба уже ничего не меняет: файлы не переписываются, и строгая проверка
    # ложно объявляла бы неудачу. Настоящая протухшая отметка старше на порядок: качалка сама
    # сохраняет их раз в час.
    _t0=$(( $(date +%s) - 120 ))
    # Запоминаем, что шло, в тот же список, по которому сторож потом снимает паузу. Иначе после
    # перезагрузки раздачи остаются стоять: паузу поставила эта функция, а поднять некому.
    qbt_get "torrents/info?filter=running" | grep -o '"hash":"[0-9a-f]*"' | cut -d'"' -f4 \
        >> /data/local/tmp/aria2/.held 2>/dev/null
    qbt_post torrents/stop "hashes=all" >/dev/null 2>&1
    _i=0
    while [ "$_i" -lt 20 ]; do
        sleep 1; _i=$((_i + 1))
        _stale=0
        for _f in "$_d"/*.fastresume; do
            [ -f "$_f" ] || continue
            [ "$(stat -c %Y "$_f" 2>/dev/null || echo 0)" -lt "$_t0" ] && _stale=1
        done
        [ "$_stale" = 0 ] && return 0
    done
    return 1
}
qbt_ok()    { qbt_get app/version | grep -q 'v[0-9]'; }

# --- Kodi --------------------------------------------------------------------
# Только POST: на GET Kodi отвечает «Bad client permission» — защита от запросов, подсунутых
# ссылкой. Нужны включённые веб-интерфейс и «управление от приложений на других системах».
kodi_rpc() {
    _b="$1"
    { printf 'POST /jsonrpc HTTP/1.1\r\nHost: %s\r\nContent-Type: application/json\r\nContent-Length: %d\r\nConnection: close\r\n\r\n%s' \
        "$LIB_KODI" "${#_b}" "$_b"; sleep 2; } | timeout 15 nc 127.0.0.1 8090 2>/dev/null | tail -1
}
kodi_playing() { kodi_rpc '{"jsonrpc":"2.0","id":1,"method":"Player.GetActivePlayers"}' | grep -q '"playerid"'; }

# --- прочее ------------------------------------------------------------------
# Обрезает файл до последних $3 строк, когда он перерос $2 байт.
rotate_one() {
    [ -f "$1" ] || return 0
    _sz=$(stat -c %s "$1" 2>/dev/null || echo 0)
    [ "$_sz" -lt "$2" ] && return 0
    tail -n "$3" "$1" > "$1.trim" 2>/dev/null && mv "$1.trim" "$1"
}

# Диск на месте. Проверяем каталог Movies, а не просто Video: при половинчатом монтировании
# верхняя папка может существовать пустой. Раньше две разные проверки расходились во мнениях.
disk_ready() { [ -d "$LIB_HDD/Video/Movies" ]; }
