#!/system/bin/sh
# Хук завершения закачки. Качалка зовёт его так:
#     qbt-complete.sh "%I" "%C" "%F"
# то есть хеш раздачи, число файлов и путь к содержимому — ровно в том порядке,
# в каком аргументы ждёт sort.sh (gid, число файлов, путь), так что переходник
# между ними не нужен.
#
# Зачем вообще обёртка: sort.sh уносит файлы из Download в медиатеку, а задача
# у качалки остаётся. При следующем запуске она не находит файлов, помечает
# раздачу как битую и может начать качать те же 60 ГБ заново. Поэтому после
# успешной раскладки задачу убираем — файлы при этом не трогаем, они уже уехали.
BIN=/data/local/tmp/aria2
# Общие функции — журнал, обращение к качалке и к Kodi, ротация, проверка диска.
# Вынесены в один файл 14.09.2026: до этого копии жили в девяти скриптах и расходились
# в мелочах (обрезка заголовков HTTP, таймауты), из-за чего работали по случайности.
. /data/local/tmp/aria2/lib.sh
LOG=$BIN/sort.log
# Журнал читает Telegram-бот (он живёт в Termux под другим пользователем) — чтобы
# написать «фильм лежит в Фильмах как …». Без чтения для всех он молчит.
touch "$LOG" 2>/dev/null; chmod 644 "$LOG" 2>/dev/null
QBT=127.0.0.1:8080


# Раздача с одним включённым файлом «завершается» после каждой серии, и качалка
# зовёт этот хук. Раскладывать при этом НЕЛЬЗЯ: на exFAT все файлы раздачи имеют
# полный размер с самого начала (драйвер забивает их нулями), поэтому sort.sh не
# отличает докачанную серию от пустой болванки и уносит в медиатеку всё подряд.
# Так 10.09 в медиатеку уехали девять пустышек, а задача была снята с качалки.
# Поэтому: пока в раздаче есть файл, скачанный не полностью, — ничего не трогаем.
unfinished=$({ printf 'GET /api/v2/torrents/files?hash=%s HTTP/1.1\r\nHost: %s\r\nConnection: close\r\n\r\n' "$1" "$QBT"; sleep 3; } \
    | timeout 20 nc 127.0.0.1 8080 2>/dev/null | tail -1 | sed 's/},{/\n/g' \
    | awk -v skip=" $(tr '\n' ' ' < "$BIN/series/$1.skip" 2>/dev/null) " '{
        i=""; if (match($0,/"index":[0-9]+/)) i=substr($0,RSTART+8,RLENGTH-8)
        if (i != "" && index(skip, " " i " ")) next
        if (match($0,/"progress":[0-9.eE+-]+/)) { p=substr($0,RSTART+11,RLENGTH-11)+0; if (p < 1) n++ } } END{ print n+0 }')

if [ "${unfinished:-0}" -gt 0 ]; then
    log "раскладку отложил: в раздаче ещё $unfinished недокачанных файлов"
    FQ_ONCE=1 sh "$BIN/filequeue.sh" 2>/dev/null
    exit 0
fi

# Сначала — очередь файлов: докачанная серия переводится в «не качать», следующая
# включается. Это должно случиться ДО того, как раскладка унесёт файл в медиатеку:
# иначе качалка хватится пропавшего файла и перекачает его заново.
FQ_ONCE=1 sh "$BIN/filequeue.sh" 2>/dev/null

# Сериал: запоминаем, какие серии сейчас уедут в медиатеку, — по этому списку series.sh
# при обновлении темы включит только новые.
sh "$BIN/series.sh" done "$1" 2>/dev/null

"$BIN/sort.sh" "$1" "$2" "$3"

# Раскладка прошла, если папки раздачи в Download больше нет.
case "$3" in
    */Download/*) top="${3#*/Download/}"; top="${top%%/*}" ;;
    *) exit 0 ;;
esac
DL=/mnt/media_rw/FA9E-9466/Download
if [ -e "$DL/$top" ]; then
    log "  задачу оставляю: «$top» ещё лежит в Download"
    exit 0
fi

b="hashes=$1&deleteFiles=false"
resp=$({ printf 'POST /api/v2/torrents/delete HTTP/1.1\r\nHost: %s\r\nContent-Type: application/x-www-form-urlencoded\r\nContent-Length: %d\r\nConnection: close\r\n\r\n%s' \
    "$QBT" "${#b}" "$b"; sleep 2; } | timeout 12 nc 127.0.0.1 8080 2>/dev/null | head -1)
case "$resp" in
    *200*) log "  задача убрана из качалки: файлы уже в медиатеке"
           # Куски невыбранных серий качалка держит в «.<хеш>.parts» рядом с раздачами.
           rm -f "$BIN/series/$1.skip" "$DL/.$1.parts" ;;
    *)     log "  задачу убрать не вышло ($resp) — уберите вручную, иначе качалка перекачает раздачу" ;;
esac
