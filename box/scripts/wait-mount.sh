#!/system/bin/sh
# Ждёт, пока vold смонтирует внешний диск (до ~2 минут), затем запускает переданную команду.
# Если диск не появился (унесли к ПК) — команда всё равно стартует:
# качалка останется живой, просто не сможет писать на диск.
# Права на создаваемые файлы. Качалка ставит себе umask 0077, то есть файлы выходят
# с правами 600, а каталоги 700 — доступные только владельцу. На exFAT это не мешало:
# права там навязывались опциями монтирования. На ext4 они настоящие, и с 600 файл
# не откроют ни сама качалка (она работает от shell, а владельцем файлов оказывается
# media_rw), ни Kodi — он ходит под своим uid и читает как «прочие». 002 даёт файлам
# 664, каталогам 775: владелец и группа media_rw пишут, остальные читают.
umask 002

i=0
while [ ! -d /mnt/media_rw/FA9E-9466/Download ] && [ $i -lt 60 ]; do
  sleep 2
  i=$((i+1))
done

# Своя страница файлового менеджера подставляется здесь, а не только в aria2.rc:
# init помнит команду с момента загрузки, и правка .rc подхватится лишь при следующей.
# Так «start fileweb» поднимает нужные параметры уже сейчас, а после перезагрузки
# они придут из .rc и второй раз не добавятся.
case " $* " in
  *" --assets "*)     exec "$@" ;;
  *" --port 8777 "*)  exec "$@" --assets /data/local/tmp/aria2/fileui \
                                --hidden .diskinfo.json,.ugoos-backup.new,.control ;;
  *)                  exec "$@" ;;
esac
